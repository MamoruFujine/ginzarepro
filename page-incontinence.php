          </h2>
          <div class="contents__text">
			<p>尿失禁の検査にもいくつか種類があるので解説していきます。<br><br></p>
            
			<h3 class="doctor__biography--name">尿検査</h3>
            <p>患者様の尿を採取し、成分から尿路感染症の有無などを確認します。最も簡単に検査できる方法の1つでしょう。<br><br></p>

			<h3 class="doctor__biography--name">膀胱鏡検査</h3>
            <p>管状の器具である膀胱鏡を尿道から膀胱内に挿入し、検査を行います。一般的に局所麻酔や全身麻酔をして行われますが、検査中は軽度の不快感があったり尿意を感じたりします。<br><br></p>

			<h3 class="doctor__biography--name">チェーン膀胱造影検査</h3>
            <p>チェーンのついたカテーテルを膀胱に挿入し、造影剤を使用して膀胱と尿道のX線画像を撮影する検査です。腹圧性尿失禁の疑いがある場合には、必ず行います。<br><br></p>

			<h3 class="doctor__biography--name">尿流動態検査</h3>
            <p>尿の排出や尿路の機能を確認するために行われる検査方法の一つです。膀胱に生理食塩水を入れて尿がたまっている状況で、排尿状態をシミュレーションしながら検査を行います。<br><br></p>

			<h3 class="doctor__biography--name">padテスト</h3>
            <p>給水シートを使用し、決められた動作や運動を行った後、尿の量や尿漏れの頻度を測定する検査です。水分摂取後、60分間実施します。腹圧性尿失禁の疑いがある場合、必要な検査になります。<br><br></p>

			<h3 class="doctor__biography--name">内診台での診察</h3>
            <p>医師に、尿道の動きや尿漏れ具合を実際に確認してもらう方法です。咳をしてお腹に力を入れながら検査を行う場合もあります。また、骨盤の中にある臓器が膣から出てしまう骨盤臓器脱の疑いがないかも同時に確認します。</p>

