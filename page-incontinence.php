        <h2 class="contents__heading"><span class="contents__heading--text">尿失禁の種類</span></h2>
        <div class="contents__text">
            <h3 class="doctor__biography--name">腹圧性尿失禁</h3>
            <p>腹圧性尿失禁とは、腹圧が急激に上昇するときに尿漏れが起こります。女性の尿失禁の中で最も多いといわれています。</p>
            <p>具体的には、くしゃみや咳、重い荷物を持ち上げた時などに腹圧がかかり、尿漏れが発生しやすいです。</p>
            <p>特に、尿道を支える筋肉や組織の骨盤底筋群の筋肉が弱い場合に起こる可能性が高くなります。</p>
            <p>出産や加齢、長時間の重労働、肥満や喘息なども骨盤底筋を痛める原因になり、結果として腹圧性尿失禁を引き起こすことがあるでしょう。<br><br></p>

            <h3 class="doctor__biography--name">切迫性尿失禁</h3>
            <p>切迫性尿失禁とは、尿意を感じた時に突然尿が漏れてしまう状態です。尿意を感じると我慢することが難しく、意識的な制御が難しいため、尿漏れにつながってしまいます。</p>
            <p>トイレが極端に近くなったり、トイレに駆け込んだりすることも増えるので、日常生活に支障をきたす可能性があるでしょう。</p>
            <p>神経系の問題によって引き起こされる場合は原因が明らかですが、特に原因がない場合も膀胱が勝手に収縮することがあります。また、女性の場合は骨盤臓器脱によって引き起こされることもあります。<br><br></p>

            <h3 class="doctor__biography--name">溢流性（いつりゅうせい）尿失禁</h3>
            <p>溢流性尿失禁とは、排尿のコントロールが困難になる状態を指します。具体的には、自分で排尿したくてもできない状態にも関わらず、少しずつ尿が漏れ出してしまいます。尿が漏れ続けるので、常に尿が溢れいるような感覚があります。</p>
            <p>よくある原因の1つとして前立腺肥大症があり、溢流性尿失禁は男性に多く見られるというのが特徴です。他にも、神経系の障害や子宮癌の術後などに発生する神経機能の低下によって発生する場合があります。<br><br></p>

            <h3 class="doctor__biography--name">機能性尿失禁</h3>
            <p>機能性尿失禁とは、排尿機能に問題がなくても、筋力の低下や認知症により起こる尿失禁です。症状としては、尿漏れや頻尿、歩行が困難なためトイレに間に合わない、認知症による排尿障害などがあげられます。</p>
            <p>治療方法は、症状によってさまざまですが、それぞれの原因となる疾患に対して治療が行われます。また、医師との相談も必要ですが、介護や環境も含めて改善方法を検討する必要が生じてくるでしょう。</p>
