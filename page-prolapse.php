    <article class="contents__article" id="">
        <h2 class="contents__heading">
            <span class="contents__heading--text">骨盤臓器脱とは</span>
        </h2>
        <div class="contents__text">
            <p>骨盤臓器脱とは、女性の骨盤内の臓器が正常な位置からずれて下垂する状態を指します。子宮や膀胱、直腸などが骨盤底筋群の弱体化や損傷によって支えが不十分になり、下腹部や腰部の圧力によって骨盤内に下がってきてしまう疾患です。</p>
            <p>加齢や出産等の要因によって骨盤底筋群が弱体化し、正常な位置を保てなくなることが原因といわれています。</p>
            <p>女性特有の疾患で発症率も高い病気ですが、恥ずかしさから受診していない方が多いのも現状です。</p>
        </div>
    </article>
    
    <article class="contents__article" id="">
        <h2 class="contents__heading"><span class="contents__heading--text">骨盤臓器脱の種類</span></h2>
        <div class="contents__text" style="padding: 10px; display:flow-root;">
            <p>骨盤臓器脱には、以下のような種類があります。</p>
        </div>
        <div class="contents__img--center">
            <img class="" src="https://ginzarepro.jp/wp-content/uploads/2023/09/pelvic_organ_prolapse_verti.jpg" alt="骨盤臓器脱の種類" width="602" height="757"/>
        </div>
        <div class="contents__text">
            <h3 class="doctor__biography--name">子宮脱</h3>
            <p>子宮が膣内に下垂し、膣から出てくる状態です。骨盤臓器脱の中でも、比較的よくある症状です。<br><br></p>
            <h3 class="doctor__biography--name">膀胱瘤</h3>
            <p>膀胱が膣に向かって下垂する症状です。尿道の支えもなくなり、進行すると尿道が折れ曲がってしまいます。尿失禁や排尿困難などの症状を引き起こします。<br><br></p>
            <h3 class="doctor__biography--name">直腸瘤</h3>
            <p>直腸が膣に向かって下垂し、膣外に突出する状態です。便秘や排便困難などの症状を引き起こします。<br><br></p>
            <h3 class="doctor__biography--name">小腸瘤（膣断端脱）</h3>
            <p>子宮摘出後、膣の奥の部分が小腸を巻き込んで下垂した状態です。違和感や痛み、時には腰痛を引き起こします</p>
        </div>
    </article>

        <article class="contents__article" id="">
          <h2 class="contents__heading">
            <span class="contents__heading--text">骨盤臓器脱の原因</span>
          </h2>
          <div class="contents__text">
				<p>骨盤臓器脱の原因は、妊娠や出産、年齢を重ねたことによる筋力低下などが考えられます。分娩や加齢に伴って骨盤底筋群が弱まり、臓器の下垂が起こります。</p>
				<p>また、重いものを持ち上げることや激しい運動、肥満なども骨盤臓器脱の原因となります。腹圧がかかったり、骨盤底筋群に負荷がかかったりするため、骨盤臓器脱出のリスクが高まります。</p>
				<p>これらのうち、1つの要因だけではなく、複数の要素が組み合わさって骨盤臓器脱が発生する場合もあります。</p>
          </div>
        </article>


        <article class="contents__article" id="">
          <h2 class="contents__heading">
            <span class="contents__heading--text">骨盤臓器脱の症状</span>
          </h2>
          <div class="contents__text">
				<p>骨盤臓器脱の症状は、下腹部や股に何か挟まっているような違和感や、陰部に何か触れるというのが初期症状です。違和感だけではなく、頻尿や便秘、排便や排尿困難を伴うこともあります。</p>
				<p>初期の場合は、腹圧がかかった時や活動した後に症状が出ますが、進行するにつれて常に臓器が飛び出している状態になります。重度の場合は、膣壁などが下着にこすれて出血することもあり、日常生活に著しく支障をきたします。</p>
          </div>
        </article>
        
        <article class="contents__article" id="">
          <h2 class="contents__heading">
            <span class="contents__heading--text">骨盤臓器脱になりやすい人の特徴</span>
          </h2>
          <div class="contents__text">
				<p>多産や難産、その他、年齢を重ねている女性は骨盤臓器脱のリスクが高まります。出産によって骨盤底筋群が弱まっている上に、閉経後にエストロゲン低下により支えが弱くなるためです。</p>
				<p>また、過度な運動をする方、重いものを持つ仕事などに従事している方、長期間の便秘や肥満に悩んでいる方も注意が必要です。慢性的に骨盤底筋群に負担をかけてしまうため、結果として骨盤臓器脱のリスクが高まります。</p>
          </div>
        </article>

        <article class="contents__article" id="">
          <h2 class="contents__heading">
            <span class="contents__heading--text">骨盤臓器脱の治療</span>
          </h2>
          <div class="contents__text">
				<p>骨盤臓器脱の治療は、症状や程度によって異なります。基本的には、薬による治療は無効で、保存的治療や手術が必要です。詳細は、以下で解説します。<br><br></p>
          </div>
            <div class="contents__text">
                <h3 class="doctor__biography--name">保存的治療</h3>
                <p>保存的治療とは、手術ではなく、症状改善や緩和を目指す治療方法です。主に何らかの理由で手術を受けられない方、手術までの待機期間の方などに行います。</p>
                <p>種類が豊富にあるので、ご自身に合った方法を選択するようにしましょう<br><br></p>
                
                <h4 style="font-weight:bold;">・骨盤底の筋肉のトレーニング<h4>
				<p>腹圧がかからないように、膣や肛門を締めるトレーニングをします。骨盤底筋を鍛えることで症状の軽減が可能です。自身の生活の中で繰り返し行う必要があります。<br><br></p>
                
                <h4 style="font-weight:bold;">・ペッサリー療法<h4>
				<p>膣内にシリコン素材のリングペッサリーを挿入し臓器の下垂を防ぎます。膣内の炎症を起こしやすいので3～4か月ごとに定期的な交換が必要となります。<br><br></p>
                
                <h4 style="font-weight:bold;">・フェミクッション<h4>
				<p>下着のように着用することができ、圧迫により臓器の脱出を防ぎます。自分で装着可能で、定期的な通院が不要です。<br><br></p>
                
                <h4 style="font-weight:bold;">・スターフォーマー<h4>
				<p>座っているだけでインナーマッスルを鍛えることができるチェアです。脱衣不要で、椅子に座るだけで効果があります。過剰な出力でなければ痛みもなく、1回の治療時間は約20～30分程度で終了です。<br><br></p>
            </div>
            <div class="contents__text">
                <h3 class="doctor__biography--name">手術による治療</h3>
                <p>骨盤臓器脱の手術による治療は、症状や程度、患者様の年齢などによって医師が判断します。</p>
                <p>具体的な術式として、メッシュ手術（TVM手術）、腹腔鏡下仙骨膣固定術（LSC手術）やロボット支援下仙骨腟固定術（RSC手術）などが行われています。その他、子宮摘出術や膣縫縮術、膣の閉鎖があります。</p>
				<p>短時間で手術が可能なものや、再発リスクがあるものなど、メリットデメリットがあります。医師からの説明をしっかりと聞き、自身に合った術式を選択しましょう。</p>
            </div>
            
        </article>

